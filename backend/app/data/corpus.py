def _item(
    title: str,
    category: OpportunityCategory,
    organization: str,
    url: str,
    *,
    country: str | None = None,
    remote: RemoteStatus = RemoteStatus.UNKNOWN,
    deadline: str | None = None,
    skills: list[str] | None = None,
    preferred: list[str] | None = None,
    compensation_min: int | None = None,
    compensation_max: int | None = None,
    currency: str | None = None,
    period: str | None = None,
    summary: str | None = None,
    source_key: str = "fixture",
) -> dict[str, Any]:
    return {
        "title": title,
        "category": category,
        "organization_name": organization,
        "source_url": url,
        "location_country": country,
        "remote_status": remote,
        "deadline": deadline,
        "required_skills": skills or [],
        "preferred_skills": preferred or [],
        "compensation_min": compensation_min,
        "compensation_max": compensation_max,
        "compensation_currency": currency,
        "compensation_period": period,
        "summary": summary or title,
        "source_key": source_key,
    }


